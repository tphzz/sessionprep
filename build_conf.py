# Core application metadata
APP_NAME = "sessionprep"

# Paths
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
ICON_DIR = os.path.join(BASE_DIR, "sessionprepgui", "res")
VERSION_FILE = os.path.join(BASE_DIR, "sessionpreplib", "_version.py")
BUILD_VERSION_FILE = os.path.join(BASE_DIR, "sessionpreplib", "_build_version.py")
_BUILD_VERSION_MARKER = "# Generated by SessionPrep build scripts."
BUILD_VERSION_MODULE = "sessionpreplib._build_version"

# Output directory names
